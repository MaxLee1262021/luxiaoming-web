-- DEV-SHR-002. Deliberate extensions: rule_mode preserves return-to-global
-- history; observe_days freezes observation policy; unique settlement id includes
-- staff identity; acknowledgment and appeal difference need persistent fields.
CREATE TABLE IF NOT EXISTS benefit_rule (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 ver INT NOT NULL,
 beneficiary_type VARCHAR(10) NOT NULL,
 party_id VARCHAR(32) NULL,
 rule_mode VARCHAR(10) NOT NULL DEFAULT 'custom',
 rate_photo_bp INT NOT NULL,
 rate_video_bp INT NOT NULL,
 rate_combo_bp INT NOT NULL,
 rate_peripheral_bp INT NOT NULL,
 eff_at DATETIME NOT NULL,
 reason VARCHAR(255) NOT NULL,
 operator VARCHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_scope_ver (beneficiary_type,party_id,ver),
 UNIQUE KEY uk_benefit_version (ver),
 KEY idx_lookup (beneficiary_type,party_id,eff_at DESC,ver DESC),
 CONSTRAINT ck_benefit_rates CHECK (rate_photo_bp BETWEEN 0 AND 10000 AND rate_video_bp BETWEEN 0 AND 10000 AND rate_combo_bp BETWEEN 0 AND 10000 AND rate_peripheral_bp BETWEEN 0 AND 10000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS benefit_ledger (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 biz_no VARCHAR(32) NOT NULL,
 beneficiary_type VARCHAR(10) NOT NULL,
 party_id VARCHAR(32) NOT NULL,
 category VARCHAR(12) NOT NULL,
 net_amount_fen BIGINT NOT NULL,
 rate_bp INT NOT NULL,
 rate_mode VARCHAR(10) NOT NULL,
 rule_ver INT NOT NULL,
 commission_fen BIGINT NOT NULL,
 observe_days INT NOT NULL DEFAULT 7,
 status VARCHAR(12) NOT NULL DEFAULT 'est',
 zero_reason VARCHAR(32) NULL,
 customer_openid VARCHAR(64) NULL,
 is_rebuy TINYINT(1) NOT NULL DEFAULT 0,
 paid_at DATETIME NOT NULL,
 done_at DATETIME NULL,
 settle_id VARCHAR(32) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_biz_party (biz_no,beneficiary_type,party_id),
 KEY idx_party_status (beneficiary_type,party_id,status),
 KEY idx_settle (settle_id),
 KEY idx_obs_scan (status,done_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS svc_settlement (
 settle_id VARCHAR(32) PRIMARY KEY,
 period CHAR(7) NOT NULL,
 staff_id VARCHAR(32) NOT NULL,
 item_count INT NOT NULL DEFAULT 0,
 amount_fen BIGINT NOT NULL DEFAULT 0,
 base_salary_fen BIGINT NOT NULL DEFAULT 0,
 offset_fen BIGINT NOT NULL DEFAULT 0,
 makeup_fen BIGINT NOT NULL DEFAULT 0,
 payable_fen BIGINT NOT NULL DEFAULT 0,
 status VARCHAR(12) NOT NULL DEFAULT 'draft',
 appeal_until DATE NULL,
 confirmed_at DATETIME NULL,
 acknowledged_at DATETIME NULL,
 paid_at DATETIME NULL,
 voucher_url VARCHAR(255) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_period_staff (period,staff_id),
 KEY idx_status (status,period)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS svc_appeal (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 settle_id VARCHAR(32) NOT NULL,
 ledger_id BIGINT NOT NULL,
 staff_id VARCHAR(32) NOT NULL,
 reason VARCHAR(500) NOT NULL,
 evidence_url VARCHAR(255) NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'pending',
 revise_amount_fen BIGINT NOT NULL DEFAULT 0,
 l1_note VARCHAR(500) NULL,
 l1_by VARCHAR(64) NULL,
 l1_at DATETIME NULL,
 l2_note VARCHAR(500) NULL,
 l2_by VARCHAR(64) NULL,
 l2_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_settle (settle_id),
 KEY idx_staff (staff_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
