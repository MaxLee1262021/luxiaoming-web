"use strict";
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { startGeneralFixture } = require('../../server/tests/fixtures/general-workbench-browser.cjs');
test('general desk workflows run independently while original desk preserves its flow', { skip: process.env.RUN_GENERAL_BROWSER !== '1', timeout: 120000 }, async t => {
  const playwright = require(process.env.SVC_PLAYWRIGHT_MODULE || 'playwright');
  const fixture = await startGeneralFixture();
  const browser = await playwright.chromium.launch({ headless: true, executablePath: process.env.SVC_BROWSER_EXECUTABLE || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const page = await browser.newPage({ viewport: { width: 1512, height: 1050 }, timezoneId: 'Asia/Shanghai' });
  const output = path.resolve(__dirname, '../../../outputs/general-workbench-development-20261120'); fs.mkdirSync(output, { recursive: true });
  const report = { testOnly: true, realDatabaseAccess: false, status: 'running', checks: [], pageErrors: [] };
  page.on('pageerror', error => report.pageErrors.push(error.message)); page.setDefaultTimeout(12000);
  // Simulate the production transport capability for legacy forms, while all
  // authenticated business requests still hit this isolated memory fixture.
  await page.route('**/api/health', async route => {
    const response = await route.fetch(), body = await response.json();
    await route.fulfill({ response, json: { ...body, mode: 'mysql', ok: true, data: { ...body.data, ready: true } } });
  });
  const writes = []; page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname.startsWith('/api/kf/')) writes.push(new URL(request.url()).pathname); });
  t.after(async () => { fs.writeFileSync(path.join(output, 'browser-check.json'), JSON.stringify(report, null, 2)); await browser.close(); await fixture.close(); });
  try {
    await page.goto(fixture.url);
    await page.getByPlaceholder('账号', { exact: true }).fill(fixture.accounts.admin.account);
    await page.getByPlaceholder('密码', { exact: true }).fill(fixture.accounts.admin.password);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByPlaceholder('账号', { exact: true }).waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '总工作台', exact: true }).click();
    const desk = page.locator('[data-page-key="svcGeneralWorkbench"]');
    await desk.getByRole('heading', { name: '总工作台', exact: true }).waitFor();
    const tableRow = number => desk.locator('tr').filter({ hasText: 'QA-GENERAL-' + number });
    await tableRow(3).getByRole('button', { name: '登记派单', exact: true }).waitFor();
    for (const label of ['确认时间', '登记派单', '改期', '详情']) assert.equal(await tableRow(3).getByRole('button', { name: label, exact: true }).count(), 1);
    for (const label of ['登记派单', '改期', '转派', '详情']) assert.equal(await tableRow(1).getByRole('button', { name: label, exact: true }).count(), 1);
    report.checks.push('all six row-action kinds and screenshot status arrangements are present');
    assert.equal((await desk.innerText()).includes('13912345678'), false);
    assert.equal((await desk.innerHTML()).includes('13912345678'), false);
    await page.screenshot({ path: path.join(output, 'general-desktop.png'), fullPage: true });
    await tableRow(3).getByRole('button', { name: '登记派单', exact: true }).click();
    const dialog = page.getByRole('dialog').filter({ hasText: '确认时间' }).last();
    await dialog.getByRole('button', { name: '确认时间并下一步', exact: true }).click();
    await dialog.getByRole('button', { name: '提交派单', exact: true }).waitFor();
    assert.equal(fixture.store.snapshot().orders.find(row => row.order_no === 'QA-GENERAL-3').service_status, 'confirmed');
    report.checks.push('wizard explicitly saves confirmation and reaches assignment without assigning automatically');
    await page.screenshot({ path: path.join(output, 'general-assignment-wizard.png'), fullPage: true });
    await dialog.getByRole('button', { name: /取消|关闭/, exact: false }).first().click();
    await page.getByText('跟进与完成', { exact: true }).click();
    const oldDesk = page.locator('[data-page-key="svcFollowup"]');
    await oldDesk.locator('tr').filter({ hasText: 'QA-GENERAL-3' }).getByRole('button', { name: /登记派单|安排摄影师/ }).click();
    const oldDialog = page.getByRole('dialog').filter({ hasText: '登记派单' }).last();
    await oldDialog.waitFor();
    assert.equal(await oldDialog.getByRole('button', { name: '确认时间并下一步', exact: true }).count(), 0);
    assert.equal(await oldDialog.getByText('选择日期（未来14天）', { exact: true }).count(), 0);
    await page.screenshot({ path: path.join(output, 'original-assignment-unchanged.png'), fullPage: true });
    report.checks.push('shared confirmed state remains visible in old entry and old assignment dialog has no wizard or new scheduler');
    await oldDialog.getByRole('button', { name: '关闭', exact: true }).click();
    await page.getByRole('button', { name: '总工作台', exact: true }).click();
    await tableRow(1).getByRole('button', { name: '登记派单', exact: true }).click();
    const record = page.getByRole('dialog').filter({ hasText: '进入转派' }).last(); await record.waitFor();
    assert.equal(writes.some(url => /QA-GENERAL-1\/(assign|transfer)$/.test(url)), false);
    report.checks.push('existing assignment record is read-only until an explicit transfer');
    await record.getByRole('button', { name: '关闭', exact: true }).click();
    await desk.getByRole('button', { name: '客户绑定', exact: true }).click();
    const bindings = page.getByRole('dialog', { name: '客户保护绑定', exact: true }); await bindings.waitFor();
    await bindings.getByRole('button', { name: '关闭', exact: true }).click();
    report.checks.push('embedded legacy customer bindings open and close without changing the desk route');
    await desk.getByRole('button', { name: '售后处理', exact: true }).click();
    await desk.getByRole('button', { name: '继续处理', exact: true }).click();
    await page.getByRole('button', { name: '复制订单信息', exact: true }).waitFor();
    assert.equal((await page.locator('body').innerHTML()).includes('13912345678'), false);
    assert.equal(await page.locator('input,textarea').evaluateAll(elements => elements.some(el => String(el.value || '').includes('13912345678'))), false);
    await page.screenshot({ path: path.join(output, 'general-aftersale-masked.png'), fullPage: true });
    report.checks.push('the original after-sale workflow remains in the new route and its shared drawer and notes stay masked');
    await page.locator('.el-drawer:visible .el-drawer__close-btn').click();
    await desk.getByRole('button', { name: '服务订单', exact: true }).click();
    const sidebarToggle = page.locator('button.sidebar-toggle');
    if (await sidebarToggle.getAttribute('aria-expanded') === 'true') await sidebarToggle.click();
    await page.setViewportSize({ width: 390, height: 844 });
    await desk.getByRole('heading', { name: '总工作台', exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'general-mobile.png'), fullPage: true, animations: 'disabled' });
    assert.equal(await tableRow(3).getByRole('button', { name: '详情', exact: true }).count(), 1);
    assert.deepEqual(report.pageErrors, []); report.status = 'passed';
  } catch (error) { report.status = 'failed'; report.failure = String(error.message).slice(0, 1000); await page.screenshot({ path: path.join(output, 'browser-failure.png'), fullPage: true }); throw error; }
});
